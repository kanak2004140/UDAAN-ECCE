from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.auth import get_current_user
from app.database import get_db, settings
from app.models.topic import Topic
from app.models.user import User
from app.schemas.lesson import LessonGenerateRequest, LessonResponse
from app.services.lesson_generation import LessonGenerationError, get_or_create_stored_lesson, get_stored_lesson

router = APIRouter(
    prefix="/lessons",
    tags=["Lessons"],
)


@router.post("/generate", response_model=LessonResponse)
def generate_lesson(
    request: LessonGenerateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    # Generation is a batch job (python -m app.ingestion.generate_lessons). Any
    # signed-in account, including a child's, could otherwise read unreviewed
    # drafts and spend LLM credit, so this route is for development only.
    if not settings.ALLOW_DRAFT_LESSONS:
        raise HTTPException(status_code=403, detail="Lessons are generated by the batch job, not on request")

    topic = db.query(Topic).filter(Topic.id == request.topic_id).first()
    if topic is None:
        raise HTTPException(status_code=404, detail="Topic not found")

    try:
        lesson = get_or_create_stored_lesson(db, topic, regenerate=request.regenerate)
    except LessonGenerationError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc

    return LessonResponse(
        topic_id=lesson.topic_id,
        topic_name=topic.name,
        age_group=topic.age_group,
        lesson_text=lesson.lesson_text,
        content_chunk_ids=lesson.content_chunk_ids,
        content_source_ids=lesson.content_source_ids,
        review_status=lesson.review_status,
    )


@router.get("/{topic_id}", response_model=LessonResponse)
def read_lesson(
    topic_id: UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """The stored lesson for a topic - never generates one. This is what the
    child-facing apps call: generation is a batch job, so a tap can't trigger
    a slow or paid AI call. Only approved lessons are served, unless the
    server runs with ALLOW_DRAFT_LESSONS (development).
    """
    topic = db.query(Topic).filter(Topic.id == topic_id).first()
    if topic is None:
        raise HTTPException(status_code=404, detail="Topic not found")

    lesson = get_stored_lesson(db, topic_id)
    if lesson is None or (lesson.review_status != "approved" and not settings.ALLOW_DRAFT_LESSONS):
        raise HTTPException(status_code=404, detail="This lesson is not ready yet")

    return LessonResponse(
        topic_id=lesson.topic_id,
        topic_name=topic.name,
        age_group=topic.age_group,
        lesson_text=lesson.lesson_text,
        content_chunk_ids=lesson.content_chunk_ids,
        content_source_ids=lesson.content_source_ids,
        review_status=lesson.review_status,
    )
